def retrieve_and_rerank(query, retrieve_k=8, final_k=3):
    """Bi-encoder retrieval from ChromaDB, then cross-encoder rerank.
    Returns list of dicts: text, source, section, bi_sim, rerank_score."""
    try:
        q_emb = model.encode([query], normalize_embeddings=True).tolist()
        res = collection.query(
            query_embeddings=q_emb,
            n_results=retrieve_k,
            include=['documents', 'metadatas', 'distances']
        )
    except Exception as e:
        print(f'❌ ChromaDB query error: {e}')
        return []

    docs  = res.get('documents', [[]])[0]
    metas = res.get('metadatas', [[]])[0]
    dists = res.get('distances', [[]])[0]
    if not docs:
        return []

    # cosine distance -> similarity
    candidates = []
    for doc, meta, dist in zip(docs, metas, dists):
        candidates.append({
            'text': doc,
            'source': (meta or {}).get('source', 'unknown'),
            'section': (meta or {}).get('section', ''),
            'bi_sim': round(1.0 - float(dist), 4),
        })

    # cross-encoder rerank
    try:
        pairs = [[query, c['text']] for c in candidates]
        scores = reranker.predict(pairs)
        for c, s in zip(candidates, scores):
            c['rerank_score'] = round(float(s), 4)
        candidates.sort(key=lambda x: x['rerank_score'], reverse=True)
    except Exception as e:
        print(f'⚠️ Rerank error, falling back to bi-encoder order: {e}')
        for c in candidates:
            c.setdefault('rerank_score', c['bi_sim'])
        candidates.sort(key=lambda x: x['bi_sim'], reverse=True)

    return candidates[:final_k]

