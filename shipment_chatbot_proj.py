model, collection, reranker, model_llm = load_resources()

def retrieve_and_rerank(query, retrieve_k=8, final_k=3):
    try:
        q_emb = model.encode([query], normalize_embeddings=True).tolist()
        res = collection.query(query_embeddings=q_emb, n_results=retrieve_k,
                               include=["documents", "metadatas", "distances"])
    except Exception:
        return []
    docs  = res.get("documents", [[]])[0]
    metas = res.get("metadatas", [[]])[0]
    dists = res.get("distances", [[]])[0]
    if not docs:
        return []
    candidates = []
    for doc, meta, dist in zip(docs, metas, dists):
        candidates.append({"text": doc,
                           "source": (meta or {}).get("source", "unknown"),
                           "bi_sim": round(1.0 - float(dist), 4)})
    try:
        scores = reranker.predict([[query, c["text"]] for c in candidates])
        for c, s in zip(candidates, scores):
            c["rerank_score"] = round(float(s), 4)
        candidates.sort(key=lambda x: x["rerank_score"], reverse=True)
    except Exception:
        candidates.sort(key=lambda x: x["bi_sim"], reverse=True)
    return candidates[:final_k]

class NovaUnavailable(Exception):
    """Raised when the model call fails so the UI can show a styled card."""

def query_rag(question, retrieve_k=8, final_k=3):
    chunks = retrieve_and_rerank(question, retrieve_k, final_k)
    if not chunks:
        return OUT_OF_SCOPE
    context = "\n\n---\n\n".join(c["text"] for c in chunks)
    user_message = f"Context:\n{context}\n\nQuestion: {question}"
    full_prompt = f"SYSTEM INSTRUCTIONS:\n{SYSTEM_PROMPT}\n\nUSER MESSAGE:\n{user_message}"
    try:
        answer = (model_llm.generate_content(
            full_prompt,
            generation_config={"temperature": 0.1, "max_output_tokens": 512},
        ).text or "").strip()
        if not answer:
            raise NovaUnavailable()
        return answer
    except NovaUnavailable:
        raise
    except Exception:
        # Hide raw tracebacks — signal the UI to render a friendly error card
        raise NovaUnavailable()

