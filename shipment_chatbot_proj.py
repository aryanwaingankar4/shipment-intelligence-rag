def retrieve_and_rerank(question, fetch_k=8, top_n=3):
    """Returns list of dicts: {text, source, section, embed_score, rerank_score}."""
    try:
        q_vec = model.encode([question], normalize_embeddings=True)[0].tolist()
        res = collection.query(query_embeddings=[q_vec], n_results=fetch_k)
    except Exception as e:
        print(f"❌ Retrieval failed: {e}")
        return []

    docs  = res["documents"][0]
    metas = res["metadatas"][0]
    dists = res["distances"][0]
    if not docs:
        return []

    try:
        pairs  = [[question, d] for d in docs]
        scores = reranker.predict(pairs)
    except Exception as e:
        print(f"⚠️  Rerank failed, falling back to embed order: {e}")
        scores = [(1 - d) for d in dists]

    ranked = sorted(
        zip(docs, metas, dists, scores),
        key=lambda x: x[3], reverse=True
    )[:top_n]

    return [{
        "text": d,
        "source": m["source"],
        "section": m.get("section_name", "—"),
        "embed_score": round((1 - dist) * 100, 1),
        "rerank_score": round(float(s), 3),
    } for d, m, dist, s in ranked]

