def _classify_error(answer_text: str) -> Optional[str]:
    low = answer_text.lower()
    if not answer_text.startswith("\u26a0") and "error" not in low and "quota" not in low:
        return None
    if any(m in low for m in QUOTA_MARKERS):
        return "quota"
    if any(m in low for m in AUTH_MARKERS):
        return "auth"
    if answer_text.startswith("\u26a0") or low.startswith("error"):
        return "error"
    return None


