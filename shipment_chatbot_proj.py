def _is_rate_limit(err_low):
    return any(k in err_low for k in ("429", "quota", "resource_exhausted", "rate limit", "rate_limit"))


def _is_auth_error(err_low):
    return any(k in err_low for k in ("401", "403", "api_key_invalid", "permission_denied", "unauthenticated"))


def _generate_with_retry(prompt, max_retries=4, verbose=True):
    last_exc = None
    for attempt in range(max_retries):
        try:
            return model_llm.generate_content(
                prompt,
                generation_config={"temperature": 0.1, "max_output_tokens": 512},
            )
        except Exception as e:
            last_exc = e
            err_low = str(e).lower()
            # Now also retry on dropped connections, not just 429s
            transient = (
                _is_rate_limit(err_low)
                or "connection reset" in err_low
                or "connection aborted" in err_low
                or "connectionreseterror" in err_low
            )
            if transient and attempt < max_retries - 1:
                wait = 5 * (2 ** attempt)  # 5, 10, 20, 40 seconds — much gentler
                if verbose:
                    print(f"⏳ Transient error. Retry {attempt + 1}/{max_retries - 1} in {wait}s...")
                time.sleep(wait)
                continue
            raise
    raise last_exc



def query_rag(question, retrieve_k=8, final_k=3, verbose=True):
    """Full RAG pipeline. Returns (answer, sources, chunks)."""
    t0 = time.time()

    if not question or not question.strip():
        return "Please enter a question.", [], []

    # Step 1: retrieve + rerank
    chunks = retrieve_and_rerank(question, retrieve_k, final_k)

    # Step 2: nothing retrieved -> refuse immediately
    if not chunks:
        rt = time.time() - t0
        log_query(question, [], IDK, rt)
        if verbose:
            print(f"❓ {question}\n💬 {IDK}\n📚 Sources: none\n⏱️ {rt:.2f}s")
        return IDK, [], []

    # Step 3-6: build grounded prompt
    context = "\n\n---\n\n".join(c["text"] for c in chunks)
    sources = sorted({c["source"] for c in chunks})
    user_message = f"Context:\n{context}\n\nQuestion: {question}"
    full_prompt = f"SYSTEM INSTRUCTIONS:\n{system_prompt}\n\nUSER MESSAGE:\n{user_message}"

    # Step 7-8: call Gemini (low temperature for grounded, deterministic answers)
    try:
        response = _generate_with_retry(full_prompt, verbose=verbose)
        answer = (response.text or "").strip()
        if not answer:
            answer = IDK
    except Exception as e:
        err = str(e).lower()
        # IMPORTANT: check rate-limit FIRST — Google's 429 messages often
        # also contain the words "api key", which previously caused a
        # misleading "Invalid API key" result.
        if _is_rate_limit(err):
            answer = "⚠️ Quota exceeded — wait and retry"
        elif _is_auth_error(err):
            answer = "⚠️ Invalid API key"
        else:
            answer = f"⚠️ Gemini error: {e}"
        sources, chunks = [], []  # don't cite sources for an error

    response_time = time.time() - t0
    log_query(question, chunks, answer, response_time)

    if verbose:
        print(f"❓ {question}")
        print(f"💬 {answer}")
        print(f"📚 Sources: {', '.join(sources) if sources else 'none'}")
        print(f"⏱️ {response_time:.2f}s")

    return answer, sources, chunks


